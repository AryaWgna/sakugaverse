let currentLang = localStorage.getItem('sakugaverse_lang') || 'id';
if (!DICT[currentLang]) currentLang = 'id';

const listeners = new Set();

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (!DICT[lang] || lang === currentLang) return;
  currentLang = lang;
  localStorage.setItem('sakugaverse_lang', lang);
  document.documentElement.lang = lang === 'jp' ? 'ja' : lang;
  listeners.forEach((fn) => fn(lang));
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key, ...args) {
  const val = DICT[currentLang]?.[key] ?? DICT.en[key] ?? key;
  return typeof val === 'function' ? val(...args) : val;
}
